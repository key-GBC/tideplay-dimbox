-- user 模块 P0 迁移：资料扩展 + 收货地址表
ALTER TABLE t_user
    ADD COLUMN gender TINYINT NOT NULL DEFAULT 0 COMMENT '性别:0未知 1男 2女',
    ADD COLUMN birthday DATE DEFAULT NULL COMMENT '生日',
    ADD COLUMN avatar VARCHAR(255) DEFAULT NULL COMMENT '头像URL',
    ADD COLUMN bio VARCHAR(255) DEFAULT NULL COMMENT '个人简介';

CREATE TABLE IF NOT EXISTS t_user_address (
    id BIGINT NOT NULL COMMENT '主键(雪花ID)',
    user_id BIGINT NOT NULL COMMENT '用户ID',
    receiver VARCHAR(32) NOT NULL COMMENT '收货人',
    phone VARCHAR(20) NOT NULL COMMENT '手机号',
    province VARCHAR(64) NOT NULL COMMENT '省',
    city VARCHAR(64) NOT NULL COMMENT '市',
    district VARCHAR(64) NOT NULL COMMENT '区',
    detail VARCHAR(255) NOT NULL COMMENT '详细地址',
    is_default TINYINT NOT NULL DEFAULT 0 COMMENT '是否默认:0否 1是',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除:0未删 1已删',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (id),
    KEY idx_user_address_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户收货地址表';
